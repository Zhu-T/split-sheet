// Regenerates lib/currency-data.ts from the Intl data built into Node: every current ISO 4217
// currency with its English name and practical minor-unit digits.
// Run with: node scripts/generate-currencies.mjs
import { writeFileSync } from "node:fs";

// The app's original currencies keep the digits it has always stored amounts with (ICU uses 0 for
// HUF and IDR, but existing data uses 2), so regenerating never changes existing amounts.
const LEGACY = {
  AUD: 2, BRL: 2, CAD: 2, CHF: 2, CNY: 2, CZK: 2, DKK: 2, EUR: 2, GBP: 2, HKD: 2,
  HUF: 2, IDR: 2, ILS: 2, INR: 2, ISK: 0, JPY: 0, KRW: 0, MXN: 2, MYR: 2, NOK: 2,
  NZD: 2, PHP: 2, PLN: 2, RON: 2, SEK: 2, SGD: 2, THB: 2, TRY: 2, USD: 2, ZAR: 2,
};

const names = new Intl.DisplayNames(["en"], { type: "currency" });
// Real currencies among the X-codes (the rest are metals, test codes and accounting units).
const KEEP_X = new Set(["XAF", "XCD", "XOF", "XPF"]);
const NOT_MONEY =
  /\b(Gold|Silver|Platinum|Palladium|Testing|Unknown|Special Drawing|European Composite|European Monetary|European Unit|Bond Markets|Euro Unit|Fund|RINET|WIR|Unidad|Mvdol|Sucre|Transferable|UIC|Financial|Convertible)\b/i;

const codes = Intl.supportedValuesOf("currency").filter((code) => {
  const name = names.of(code);
  const historical = /\(\d{4}/.test(name ?? ""); // e.g. "Afghan Afghani (1927–2002)"
  return name && name !== code && !historical && !NOT_MONEY.test(name) && (!code.startsWith("X") || KEEP_X.has(code));
});

for (const code of Object.keys(LEGACY)) {
  if (!codes.includes(code)) throw new Error(`Existing currency ${code} is missing from Intl data`);
}

const decimals = (code) =>
  LEGACY[code] ?? new Intl.NumberFormat("en", { style: "currency", currency: code }).resolvedOptions().maximumFractionDigits;

const body = codes.map((c) => `  ${c}: { name: ${JSON.stringify(names.of(c))}, decimals: ${decimals(c)} },`).join("\n");
writeFileSync(
  new URL("../lib/currency-data.ts", import.meta.url),
  `// Generated by scripts/generate-currencies.mjs (Node ${process.version}). Committed rather than computed at
// runtime so every browser and the server agree on the list and on decimal places.

export const CURRENCY_DATA = {
${body}
} as const;
`,
);
console.log(`Wrote ${codes.length} currencies to lib/currency-data.ts`);
